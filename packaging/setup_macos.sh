#!/bin/bash
# Provision a native Apple Silicon development checkout without changing shell profiles.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
INSTALL_BREW=1
CONFIGURE=1
for arg in "$@"; do
  case "$arg" in
    --skip-brew) INSTALL_BREW=0 ;;
    --no-configure) CONFIGURE=0 ;;
    --help|-h)
      echo 'Usage: ./packaging/setup_macos.sh [--skip-brew] [--no-configure]'
      echo 'Installs dependencies, builds SoundTouch plugin, writes build-macos-deps/env.sh, and configures OpenKJ.'
      echo 'Requires native Apple Silicon macOS, Xcode Command Line Tools, and Homebrew.'
      exit 0 ;;
    *) echo "Unknown option: $arg" >&2; exit 1 ;;
  esac
done

[[ "$(uname -s)" == Darwin && "$(uname -m)" == arm64 ]] || {
  echo 'Run this script on an Apple Silicon Mac from a native terminal (not Rosetta).' >&2; exit 1;
}
xcode-select -p >/dev/null 2>&1 || {
  echo 'Install Apple Command Line Tools with: xcode-select --install' >&2; exit 1;
}
if ! command -v brew >/dev/null; then
  [[ -x /opt/homebrew/bin/brew ]] && eval "$(/opt/homebrew/bin/brew shellenv)"
fi
command -v brew >/dev/null || {
  echo 'Install Homebrew from https://brew.sh, then rerun this script.' >&2; exit 1;
}
[[ "$(brew --prefix)" == /opt/homebrew ]] || {
  echo 'Use native Apple Silicon Homebrew at /opt/homebrew.' >&2; exit 1;
}
if (( INSTALL_BREW )); then
  # Do not upgrade an existing developer environment implicitly.
  HOMEBREW_NO_AUTO_UPDATE=1 brew bundle install --no-upgrade --file="$ROOT/packaging/Brewfile.macos"
fi

QT_PREFIX="$(brew --prefix qt)"
GST_PREFIX="$(brew --prefix gstreamer)"
SOUNDTOUCH_PREFIX="$(brew --prefix sound-touch)"
export PATH="$(brew --prefix)/bin:$QT_PREFIX/bin:$PATH"
export PKG_CONFIG_PATH="$GST_PREFIX/lib/pkgconfig:$SOUNDTOUCH_PREFIX/lib/pkgconfig:${PKG_CONFIG_PATH:-}"
export CMAKE_PREFIX_PATH="$QT_PREFIX:${CMAKE_PREFIX_PATH:-}"
for tool in cmake ninja meson python3 pkg-config curl shasum; do
  command -v "$tool" >/dev/null || { echo "Missing dependency: $tool (rerun without --skip-brew)" >&2; exit 1; }
done

# Use the same unmodified upstream plugin and Meson options as the tested build.
# Pin source and checksum; Homebrew supplies the GStreamer ABI and SoundTouch library.
GST_VERSION=1.28.8
GST_SHA256=670d888bde8242579b0d8e91f60cf337aa7be20ca7c315ebfbdd6e5a9218d104
DEPS="$ROOT/build-macos-deps"
SOURCE="$DEPS/gst-plugins-bad-$GST_VERSION"
ARCHIVE="$DEPS/gst-plugins-bad-$GST_VERSION.tar.xz"
PLUGIN_BUILD="$DEPS/soundtouch-$GST_VERSION"
mkdir -p "$DEPS"
if [[ ! -f "$ARCHIVE" ]]; then
  curl --fail --location --retry 3 \
    "https://gstreamer.freedesktop.org/src/gst-plugins-bad/gst-plugins-bad-$GST_VERSION.tar.xz" \
    --output "$ARCHIVE.download"
  mv "$ARCHIVE.download" "$ARCHIVE"
fi
echo "$GST_SHA256  $ARCHIVE" | shasum -a 256 -c -
if [[ ! -d "$SOURCE" ]]; then
  tar -xf "$ARCHIVE" -C "$DEPS"
fi
MESON_ARGS=(--buildtype=release --wrap-mode=nofallback --auto-features=disabled
  -Dsoundtouch=enabled -Dintrospection=disabled -Ddoc=disabled -Dexamples=disabled -Dtests=disabled)
if [[ -f "$PLUGIN_BUILD/meson-private/coredata.dat" ]]; then
  meson setup --reconfigure "$PLUGIN_BUILD" "$SOURCE" "${MESON_ARGS[@]}"
else
  meson setup "$PLUGIN_BUILD" "$SOURCE" "${MESON_ARGS[@]}"
fi
meson compile -C "$PLUGIN_BUILD" -j "${OPENKJ_BUILD_JOBS:-4}" gstsoundtouch
SOUNDTOUCH_PLUGIN="$PLUGIN_BUILD/ext/soundtouch/libgstsoundtouch.dylib"
codesign --force --sign - "$SOUNDTOUCH_PLUGIN"

# A disposable registry ensures validation actually loads this plugin.
REGISTRY="$(mktemp "$DEPS/registry.XXXXXXXX")"
trap 'rm -f "$REGISTRY"' EXIT
GST_REGISTRY="$REGISTRY" GST_PLUGIN_PATH_1_0="$(dirname "$SOUNDTOUCH_PLUGIN")" \
  "$GST_PREFIX/bin/gst-inspect-1.0" "$SOUNDTOUCH_PLUGIN"
GST_REGISTRY="$REGISTRY" GST_PLUGIN_PATH_1_0="$(dirname "$SOUNDTOUCH_PLUGIN")" \
  "$GST_PREFIX/bin/gst-launch-1.0" -q audiotestsrc num-buffers=8 \
  '!' audioconvert '!' pitch pitch=1.1 '!' equalizer-10bands '!' fakesink

# Source this for terminal builds or use these variables in the IDE's CMake configuration.
{
  echo '# Generated by packaging/setup_macos.sh; rerun setup after moving this checkout.'
  printf 'export PATH=%q:"$PATH"\n' "$(brew --prefix)/bin:$QT_PREFIX/bin"
  printf 'export CMAKE_PREFIX_PATH=%q:"${CMAKE_PREFIX_PATH:-}"\n' "$QT_PREFIX"
  printf 'export PKG_CONFIG_PATH=%q:"${PKG_CONFIG_PATH:-}"\n' "$GST_PREFIX/lib/pkgconfig:$SOUNDTOUCH_PREFIX/lib/pkgconfig"
  printf 'export SOUNDTOUCH_PLUGIN=%q\n' "$SOUNDTOUCH_PLUGIN"
  printf 'export GST_PLUGIN_PATH_1_0=%q:"${GST_PLUGIN_PATH_1_0:-}"\n' "$(dirname "$SOUNDTOUCH_PLUGIN")"
} > "$DEPS/env.sh"

if (( CONFIGURE )); then
  cmake -S "$ROOT" -B "$ROOT/build-macos-dev" \
    -DCMAKE_BUILD_TYPE=RelWithDebInfo \
    -DCMAKE_PREFIX_PATH="$QT_PREFIX" \
    -DOPENKJ_SOUNDTOUCH_PLUGIN="$SOUNDTOUCH_PLUGIN"
fi
{
  sw_vers
  xcrun clang --version
  brew list --versions cmake ninja pkgconf meson python@3.14 qt gstreamer sound-touch
  echo "GStreamer plugin source: $GST_VERSION ($GST_SHA256)"
} > "$DEPS/environment.txt"
echo "Setup complete. Environment report: $DEPS/environment.txt"
echo "Next: source \"$DEPS/env.sh\""
echo "      cmake --build \"$ROOT/build-macos-dev\" --parallel 4"
